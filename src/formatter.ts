/**
 * Formats a DepBlast report into a readable PR comment.
 */

import { DepBlastReport, DependencyInfo } from "./types";
import { DepBlastConfig } from "./config";
import { summarizeSecurityIssues } from "./analysers/security";

/**
 * Format bytes to human-readable string.
 */
function formatBytes(bytes: number | null): string {
  if (bytes === null) return "Unknown";
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

/**
 * Format a maintainer score (1-5) into emoji + label.
 */
function formatMaintainerScore(score: number | null): string {
  if (score === null) return "❓ Unknown";
  if (score >= 5) return "🟢 Excellent";
  if (score >= 4) return "🟢 Good";
  if (score >= 3) return "🟡 Fair";
  if (score >= 2) return "🟠 Poor";
  return "🔴 Critical";
}

/**
 * Format a license string with risk indicator.
 */
function formatLicense(license: string | null, isRisky: boolean): string {
  if (!license) return "❓ Unknown";
  if (isRisky) return `⚠️ **${license}**`;
  return `✅ ${license}`;
}

/**
 * Build the full PR comment markdown.
 */
export function formatReport(report: DepBlastReport, _config: DepBlastConfig): string {
  const lines: string[] = [];
  const { summary, dependencies } = report;

  lines.push("🐼 **DepBlast Report**");
  lines.push("");
  lines.push(`Analyzed PR **#${report.prNumber}** in **${report.repoFullName}**`);
  lines.push("");
  lines.push("---");
  lines.push("");

  // Summary section
  lines.push("### 📊 Summary");
  lines.push("");
  lines.push(`| Metric | Value |`);
  lines.push(`|--------|-------|`);
  lines.push(`| New/changed dependencies | **${summary.totalNewDeps}** |`);
  lines.push(`| Transitive dependencies | **${summary.totalTransitiveDeps}** |`);
  lines.push(`| Estimated total size impact | **${formatBytes(summary.totalSizeBytes)}** |`);

  const flags: string[] = [];
  if (summary.hasLicenseIssues) flags.push("⚠️ License issues");
  if (summary.hasSecurityIssues) flags.push("🔒 Security advisories");
  if (summary.hasHealthIssues) flags.push("❤️‍🩹 Low maintainer health");
  lines.push(`| Flags | ${flags.length > 0 ? flags.join(", ") : "✅ All clear"} |`);

  lines.push("");

  // Per-dependency breakdown
  lines.push("### 🔍 Dependency Breakdown");
  lines.push("");

  for (const dep of dependencies) {
    lines.push(formatDepSection(dep));
    lines.push("");
  }

  lines.push("---");
  lines.push("");
  lines.push(
    "_Generated by DepBlast. Configure via `.depblast.yml` in your repo root._"
  );

  return lines.join("\n");
}

function formatDepSection(dep: DependencyInfo): string {
  const lines: string[] = [];

  // Header with type badge
  const typeBadge = dep.type === "dependencies"
    ? "`📦 production`"
    : dep.type === "devDependencies"
    ? "`🛠 dev`"
    : dep.type === "peerDependencies"
    ? "`🤝 peer`"
    : "`🔀 optional`";

  lines.push(`#### ${dep.name}@${dep.version} ${typeBadge}`);

  // Quick status row
  const statuses: string[] = [];
  if (dep.sizeBytes !== null && dep.sizeBytes > 500_000) {
    statuses.push("📦 Large package");
  }
  if (dep.licenseRisk) {
    statuses.push("⚠️ License concern");
  }
  if (dep.securityIssues.length > 0) {
    const critical = dep.securityIssues.filter((s) => s.severity === "CRITICAL").length;
    if (critical > 0) {
      statuses.push(`🔴 ${critical} critical advisory(ies)`);
    } else {
      statuses.push(`🟡 ${dep.securityIssues.length} advisory(ies)`);
    }
  }
  if (dep.maintainerScore !== null && dep.maintainerScore < 3) {
    statuses.push("❤️‍🩹 Low maintenance");
  }
  if (dep.deprecated) { // deprecated added via health analysis
    statuses.push("🚫 Deprecated");
  }

  if (statuses.length > 0) {
    lines.push("");
    lines.push(`**Status:** ${statuses.join(" · ")}`);
  } else {
    lines.push("");
    lines.push("**Status:** ✅ Looks good!");
  }

  // Details table
  lines.push("");
  lines.push("| Property | Value |");
  lines.push("|----------|-------|");

  // Size
  if (dep.sizeBytes !== null) {
    lines.push(`| Bundle size (min) | ${formatBytes(dep.sizeBytes)} |`);
  } else {
    lines.push(`| Bundle size | ❓ Not available |`);
  }

  // Transitive deps
  lines.push(
    `| Transitive dependencies | **${dep.transitiveDeps.length}** package(s) |`
  );
  if (dep.transitiveDeps.length > 0) {
    // List top transitive deps
    const topTransitives = dep.transitiveDeps.slice(0, 5);
    const transitiveList = topTransitives
      .map((t) => `${t.name}@${t.version}`)
      .join(", ");
    const more = dep.transitiveDeps.length > 5
      ? ` (and ${dep.transitiveDeps.length - 5} more)`
      : "";
    lines.push(`| Top transitive deps | \`${transitiveList}\`${more} |`);
  }

  // License
  lines.push(`| License | ${formatLicense(dep.license, dep.licenseRisk)} |`);

  // Security
  if (dep.securityIssues.length > 0) {
    lines.push(`| Security | ${summarizeSecurityIssues(dep.securityIssues)} |`);
    // List top severe ones
    for (const advisory of dep.securityIssues.slice(0, 3)) {
      const cveRef = advisory.cveId ? ` [${advisory.cveId}](https://nvd.nist.gov/vuln/detail/${advisory.cveId})` : "";
      lines.push(`| | ⚠️ ${advisory.severity}: ${advisory.summary}${cveRef} |`);
    }
  } else {
    lines.push("| Security | ✅ No known vulnerabilities |");
  }

  // Maintainer health
  const scoreStr = formatMaintainerScore(dep.maintainerScore);
  lines.push(`| Maintainer health | ${scoreStr} (${dep.maintainerScore ?? "?"}/5) |`);

  if (dep.maintainerDetails) {
    if (dep.maintainerDetails.weeklyDownloads !== null) {
      const downloads = dep.maintainerDetails.weeklyDownloads >= 1000000
        ? `${(dep.maintainerDetails.weeklyDownloads / 1000000).toFixed(1)}M`
        : dep.maintainerDetails.weeklyDownloads >= 1000
        ? `${(dep.maintainerDetails.weeklyDownloads / 1000).toFixed(1)}K`
        : String(dep.maintainerDetails.weeklyDownloads);
      lines.push(`| Weekly downloads | ${downloads} |`);
    }
    if (dep.maintainerDetails.stars !== null) {
      lines.push(`| GitHub stars (approx) | ${dep.maintainerDetails.stars} |`);
    }
    if (dep.lastPublishDate) {
      const date = new Date(dep.lastPublishDate);
      const daysAgo = Math.floor((Date.now() - date.getTime()) / (1000 * 60 * 60 * 24));
      const ago = daysAgo === 0
        ? "Today"
        : daysAgo === 1
        ? "Yesterday"
        : `${daysAgo} days ago`;
      lines.push(`| Last published | ${date.toISOString().split("T")[0]} (${ago}) |`);
    }
    if (dep.maintainerCount !== null) {
      lines.push(`| Maintainers | ${dep.maintainerCount} |`);
    }
  }

  return lines.join("\n");
}
